/// RULES
void relu(float* x, const uint8_t& h, const uint8_t& w, const uint8_t& c) {
  for (int k = 0; k < c; ++k) {
    for (int i = 0; i < w; ++i) {
      for (int j = 0; j < h; ++j) {
        float& value = x[k * (w * h) + i * w + j];
        if (value < 0.f)
          value = 0.f;
      }
    }
  }
}
  
void sigmoid(float* x, const uint8_t& h, const uint8_t& w, const uint8_t& c) {
  for (int k = 0; k < c; ++k) {
    for (int i = 0; i < w; ++i) {
      for (int j = 0; j < h; ++j) {
        float& value = x[k * (w * h) + i * w + j];
        value = (1.f / (1.f + exp(-value)));
      }
    }
  }
}  
  
void conv(const float* w, const float* b,
          const float* x, float* o,
          const uint8_t& input_size_x, const uint8_t& input_size_y,
          const uint8_t& in_channels, const uint8_t& out_channels,
          const uint8_t& kernel_x, const uint8_t& kernel_y,
          const uint8_t& stride_x, const uint8_t& stride_y,
          const uint8_t& padding_x, const uint8_t& padding_y,
          float* membuf) {

  int out_size_x = (input_size_x + 2 * padding_x - kernel_x) / stride_x + 1;
  int out_size_y = (input_size_y + 2 * padding_y - kernel_y) / stride_y + 1;
  
  
  // create padded tensor
  int ptr = 0;
  for (uint8_t ci = 0; ci < in_channels; ++ci) {
    ptr += (2 * padding_x + input_size_x) * padding_y;

    for (uint8_t i = 0; i < input_size_y; ++i) {
      ptr += padding_x;

      for (uint8_t j = 0; j < input_size_x; ++j) {
        membuf[ptr] = x[ci * (input_size_x * input_size_y) + i * input_size_x + j];
        ptr += 1;
      }

      ptr += padding_x;
    }

    ptr += (2 * padding_x + input_size_x) * padding_y;
  }


  // convolution
  int out_idx = 0;
  float value = 0.f;

  for (uint8_t co = 0; co < out_channels; ++co) {
    for (uint8_t i = 0; i < (2 * padding_x + input_size_x) - kernel_x + 1; i += stride_x) {
      for (uint8_t j = 0; j < (2 * padding_y + input_size_y) - kernel_y + 1; j += stride_y) {
        

        for (uint8_t ci = 0; ci < in_channels; ++ci) {
          for (uint8_t n = 0; n < kernel_x; ++n) {
            for (uint8_t m = 0; m < kernel_y; ++m) {
              value += (membuf[(ci * ((2 * padding_x + input_size_x) * (2 * padding_y + input_size_y)) + i * (2 * padding_x + input_size_x) + j) + (n * (2 * padding_x + input_size_x) + m)] * w[co * (in_channels * kernel_x * kernel_y) + ci * (kernel_x * kernel_y) + n * kernel_x + m]);
            }
          }
        }
        
        o[out_idx] = value;
        value = 0.f;

        out_idx += 1;
      }
    }
  }


  // add bias
  for (uint8_t co = 0; co < out_channels; ++co) {
    for (uint8_t i = 0; i < out_size_x; ++i) {
      for (uint8_t j = 0; j < out_size_y; ++j) {
        o[co * (out_size_x * out_size_y) + i * (out_size_x) + j] += b[co];
      }
    }
  }
}


/// INFERENCE
void inference(const float* input, float* output) {
  float conv_bl_1_1_output[4*16*16] = {};
  float conv_bl_1_2_output[4*8*8] = {};

  float conv_bl_2_1_output[8*8*8] = {};
  float conv_bl_2_2_output[8*4*4] = {};

  float conv_bl_3_1_output[12*4*4] = {};
  float conv_bl_3_2_output[12*2*2] = {};

  float membuf[12*16*16] = {};


  // conv block 1
  conv(conv_bl_1_1_weight, conv_bl_1_1_bias,
       input, conv_bl_1_1_output,
       16, 16,
       1, 4,
       3, 3,
       1, 1,
       1, 1,
       membuf);
  relu(conv_bl_1_1_output, 16, 16, 4);
  conv(conv_bl_1_2_weight, conv_bl_1_2_bias,
       conv_bl_1_1_output, conv_bl_1_2_output,
       16, 16,
       4, 4,
       2, 2,
       2, 2, 
       0, 0,
       membuf);
  relu(conv_bl_1_2_output, 8, 8, 4);

  // conv block 2
  conv(conv_bl_2_1_weight, conv_bl_2_1_bias,
       conv_bl_1_2_output, conv_bl_2_1_output,
       8, 8,
       4, 8,
       3, 3,
       1, 1,
       1, 1,
       membuf);
  relu(conv_bl_2_1_output, 8, 8, 8);
  conv(conv_bl_2_2_weight, conv_bl_2_2_bias,
       conv_bl_2_1_output, conv_bl_2_2_output,
       8, 8,
       8, 8,
       2, 2,
       2, 2,
       0, 0,
       membuf);
  relu(conv_bl_2_2_output, 4, 4, 8);

  // conv block 3
  conv(conv_bl_3_1_weight, conv_bl_3_1_bias,
       conv_bl_2_2_output, conv_bl_3_1_output,
       4, 4,
       8, 12,
       3, 3,
       1, 1,
       1, 1,
       membuf);
  relu(conv_bl_3_1_output, 4, 4, 12);
  conv(conv_bl_3_2_weight, conv_bl_3_2_bias,
       conv_bl_3_1_output, conv_bl_3_2_output,
       4, 4,
       12, 12,
       2, 2,
       2, 2,
       0, 0,
       membuf);
  relu(conv_bl_3_2_output, 2, 2, 12);

  // conv block 4
  conv(conv_bl_4_1_weight, conv_bl_4_1_bias,
       conv_bl_3_2_output, output,
       2, 2,
       12, 1,
       2, 2,
       1, 1, 
       0, 0,
       membuf);
  sigmoid(output, 1, 1, 1);
}

